#!/usr/bin/env node
/* Official chapter 001 audiobook must publish the verified existing MP3 and never hide text or disturb progress. */
import assert from 'node:assert/strict';
import {readFileSync,existsSync,statSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {Script} from 'node:vm';
const root=resolve(fileURLToPath(new URL('../',import.meta.url)));
const read=p=>readFileSync(join(root,p),'utf8');
const file='assets/audio/audiobook/part-01/volume-01/chapter-001.mp3';
assert.ok(existsSync(join(root,file)),'Published MP3 not committed');
const data=readFileSync(join(root,file));
assert.ok(data.length>4_000_000 && data.length<20_000_000,'Unexpected audiobook size');
assert.equal(data.subarray(0,3).toString('utf8'),'ID3','Not a valid MP3 ID3 header');
const page=read('chapters/volume-01/chapter-001.html');
const volume=read('volumes/volume-01.html');
assert.ok(page.includes('controls preload="none"'),'No autoplay or prefetch allowed');
assert.ok(!/<audio[^>]+autoplay/.test(page),'Audio must only start by user action');
assert.ok(page.includes(file.replace('assets/audio','../../assets/audio')),'MP3 relative source path missing');
assert.ok(page.includes('download="第零序列_死亡与重生_子悦_ZiYue_V4.mp3"'));
assert.ok(page.includes('chapter-001.mp3?v=zi-yue-v4'),'Must bypass any cached old Amy voice');
assert.ok(page.includes('Zi Yue 子悦 · Eleven v4'),'Official audiobook must be Zi Yue V4');
assert.ok(volume.includes('子悦 Zi Yue 女声有声版'),'Volume index must identify new official voice');
assert.ok(volume.includes('chapter-001.html#zs-audiobook-player'),'Chapter directory audiobook link missing');
assert.ok(page.includes('<p>滴答。</p>')&&page.includes('——【零】。'),'Original story body must remain unchanged');
assert.equal((page.match(/<div class="article">/g)||[]).length,1,'Must retain one original story article');
const js=read('assets/js/chapter-audiobook.js');
assert.doesNotThrow(()=>new Script(js,{filename:'chapter-audiobook.js'}));
assert.ok(!js.includes('localStorage'),'Audiobook must not touch reading progress');
assert.ok(js.includes('#zs-audio.is-playing .zs-play'),'BGM should pause on narration start');
assert.ok(read('assets/css/chapter-audiobook.css').includes('@media(max-width:650px)'),'Mobile player styling required');
const mp3Two='assets/audio/audiobook/part-01/volume-01/chapter-002.mp3';
const secondBinary=readFileSync(join(root,mp3Two));
assert.ok(secondBinary.length>2_000_000 && secondBinary.length<12_000_000,'Second audiobook audio is unexpectedly small or large');
assert.equal(secondBinary.subarray(0,3).toString('utf8'),'ID3','Chapter 2 is not MP3');
const pageTwo=read('chapters/volume-01/chapter-002.html');
assert.ok(pageTwo.includes('第二章 · 子悦中文女声有声版')&&pageTwo.includes('Zi Yue 子悦 · Eleven v4'),'Correct second chapter voice and model required');
assert.ok(pageTwo.includes('chapter-002.mp3?v=zi-yue-v4'),'Use verified official MP3 with cache bust');
assert.ok(pageTwo.includes('download="第零序列_熟悉的日期_子悦_ZiYue_V4.mp3"'),'Second chapter MP3 download missing');
assert.ok(pageTwo.includes('controls preload="none"')&&!/<audio[^>]+autoplay/.test(pageTwo),'Second chapter must be opt-in');
assert.ok(pageTwo.includes('assets/js/chapter-audiobook.js?v=1'),'Second chapter should coordinate BGM');
assert.ok(pageTwo.includes('<p>上午十点零七分。</p>')&&pageTwo.includes('<p>数秒后，数字消失。</p>'),'Second chapter story boundaries lost');
assert.equal((pageTwo.match(/<div class="article">/g)||[]).length,1,'Original chapter body must remain');
assert.equal((pageTwo.match(/<div class="article">[\s\S]*?<div class="pager">/g)||[]).length,1,'Original chapter navigation must remain');
assert.ok(volume.includes('chapter-002.html#zs-audiobook-player'),'Second chapter listening link missing in volume index');
const mp3Three='assets/audio/audiobook/part-01/volume-01/chapter-003.mp3';
const thirdBinary=readFileSync(join(root,mp3Three));
assert.ok(thirdBinary.length>2_000_000 && thirdBinary.length<12_000_000,'Third audiobook audio is unexpectedly small or large');
assert.equal(thirdBinary.subarray(0,3).toString('utf8'),'ID3','Chapter 3 is not a full MP3');
const pageThree=read('chapters/volume-01/chapter-003.html');
assert.ok(pageThree.includes('第三章 · 子悦中文女声有声版')&&pageThree.includes('Zi Yue 子悦 · Eleven v4'),'Correct Chapter 3 voice and model required');
assert.ok(pageThree.includes('chapter-003.mp3?v=zi-yue-v4'),'Verified official MP3 path and cache bust required');
assert.ok(pageThree.includes('download="第零序列_神魔轮回_子悦_ZiYue_V4.mp3"'),'Third chapter MP3 download missing');
assert.ok(pageThree.includes('controls preload="none"')&&!/<audio[^>]+autoplay/.test(pageThree),'Third chapter narration must be opt-in');
assert.ok(pageThree.includes('assets/js/chapter-audiobook.js?v=1'),'Third chapter should coordinate background music');
assert.ok(pageThree.includes('<p>【6. 不要假设只有我回来了。】</p>')&&pageThree.includes('<p>【0】</p>'),'Original third chapter text beginning or ending changed');
const chapterThreeBody=pageThree.split('<div class="article">',2)[1].split('<div class="pager">',2)[0];
assert.equal((chapterThreeBody.match(/<p(?:\s[^>]*)?>/g)||[]).length,58,'Original 58 story paragraphs must remain');
assert.equal((pageThree.match(/<div class="article">/g)||[]).length,1,'Original third chapter article must be preserved');
assert.ok(volume.includes('chapter-003.html#zs-audiobook-player'),'Third chapter listening link missing in volume catalog');
const mp3Four='assets/audio/audiobook/part-01/volume-01/chapter-004.mp3';
const fourthBinary=readFileSync(join(root,mp3Four));
assert.ok(fourthBinary.length>2_000_000 && fourthBinary.length<12_000_000,'Chapter 4 audiobook file missing or corrupt');
assert.equal(fourthBinary.subarray(0,3).toString('utf8'),'ID3','Fourth chapter is not valid MP3');
const pageFour=read('chapters/volume-01/chapter-004.html');
assert.ok(pageFour.includes('第四章 · 子悦中文女声有声版')&&pageFour.includes('Zi Yue 子悦 · Eleven v4'),'Chapter 4 narrator identity changed');
assert.ok(pageFour.includes('chapter-004.mp3?v=zi-yue-v4'),'Chapter 4 official MP3 URL missing');
assert.ok(pageFour.includes('download="第零序列_不一样的选择_子悦_ZiYue_V4.mp3"'),'MP3 download missing');
assert.ok(pageFour.includes('controls preload="none"')&&!/<audio[^>]+autoplay/.test(pageFour),'Narration must remain opt-in');
assert.ok(pageFour.includes('assets/js/chapter-audiobook.js?v=1'),'Narration must coordinate background music');
assert.ok(pageFour.includes('<p>重生后的第二天，顾长渊没有去寻找所谓的隐藏神器。</p>')&&pageFour.includes('<p>【请不要再次错过。】</p>'),'Chapter 4 story beginning or ending changed');
const chapterFourBody=pageFour.split('<div class="article">',2)[1].split('<div class="pager">',2)[0];
assert.equal((chapterFourBody.match(/<p(?:\\s[^>]*)?>/g)||[]).length,70,'Original Chapter 4 70 paragraphs must remain');
assert.equal((pageFour.match(/<div class="article">/g)||[]).length,1,'Original article structure lost');
assert.ok(volume.includes('chapter-004.html#zs-audiobook-player'),'Fourth chapter audio link missing in volume catalog');
const mp3Five='assets/audio/audiobook/part-01/volume-01/chapter-005.mp3';
const fifthBinary=readFileSync(join(root,mp3Five));
assert.ok(fifthBinary.length>2_000_000 && fifthBinary.length<12_000_000,'Chapter 5 audiobook is unexpectedly missing or small');
assert.equal(fifthBinary.subarray(0,3).toString('utf8'),'ID3','Fifth chapter is not valid MP3');
const pageFive=read('chapters/volume-01/chapter-005.html');
assert.ok(pageFive.includes('第五章 · 子悦中文女声有声版')&&pageFive.includes('Zi Yue 子悦 · Eleven v4'),'Chapter 5 narrator identity must remain Zi Yue');
assert.ok(pageFive.includes('chapter-005.mp3?v=zi-yue-v4'),'Chapter 5 official MP3 cache-busted URL missing');
assert.ok(pageFive.includes('download="第零序列_隐藏的序列_子悦_ZiYue_V4.mp3"'),'Chapter 5 MP3 download missing');
assert.ok(pageFive.includes('controls preload="none"')&&!/<audio[^>]+autoplay/.test(pageFive),'Chapter 5 narration must not autoplay');
assert.ok(pageFive.includes('assets/js/chapter-audiobook.js?v=1'),'Chapter 5 must pause BGM on narration start');
assert.ok(pageFive.includes('<p>封测设备在第二天下午送到。</p>')&&pageFive.includes('<p>光芒吞没一切。</p>'),'Chapter 5 story boundaries changed');
const chapterFiveBody=pageFive.split('<div class="article">',2)[1].split('<div class="pager">',2)[0];
assert.equal((chapterFiveBody.match(/<p>/g)||[]).length,79,'Chapter 5 must retain 79 original story paragraphs');
assert.equal((pageFive.match(/<div class="article">/g)||[]).length,1,'Chapter 5 article container changed');
assert.ok(volume.includes('chapter-005.html#zs-audiobook-player'),'Fifth chapter audiobook link missing from first volume');
console.log('[AUDIOBOOK] PASS: official Zi Yue v4 Chapter 1 published with a '+data.length+'-byte opt-in MP3, mobile controls, progress and BGM preserved.');
