#!/usr/bin/env node
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {Script} from 'node:vm';
const read=p=>readFileSync(p,'utf8');
const chapter='chapters/volume-32/chapter-001.html';
const page=read(chapter),previous=read('chapters/volume-31/chapter-010.html');
const article=page.match(/<div class="article">([\s\S]*?)<div class="pager">/)?.[1];
assert.ok(article,'Chapter 311 narrative article missing');
const plain=article.replace(/<[^>]+>/g,'').replace(/&(?:amp|lt|gt|quot|nbsp);/g,' ');
const han=(plain.match(/[\u3400-\u9fff]/g)||[]).length;
assert.ok(han>=3000&&han<=3500,'Chapter 311 length invalid: '+han);
assert.ok(page.includes('第311章 猎榜令')&&page.includes('全书第311章 · 正式正文'),'Chapter 311 title and serial missing');
assert.ok(page.includes('../volume-31/chapter-010.html'),'Previous chapter link broken');
assert.ok(previous.includes('../volume-32/chapter-001.html'),'Chapter 310 must link forward to 311');
assert.ok(page.includes('chapter-002.html')&&existsSync('chapters/volume-32/chapter-002.html'),'Completed volume must link forward to 312');
assert.ok(!page.includes('80级')&&!page.includes('三十年末日'),'Do not reveal private fusion rule or old timeline');
for(const name of ['顾长渊','苏紫璃','林烈','罗烬','凌天曜','梁策','重剑','剑士','猎场'])assert.ok(page.includes(name),'Continuity identity absent: '+name);
for(const name of ['古言澈','宙溟','神域秩序议会'])assert.ok(!page.includes(name),'Do not insert unintroduced arc spoilers in chapter 311');
const vol=read('volumes/volume-32.html'),part=read('parts/part-04.html'),home=read('index.html');
assert.ok(vol.includes('第三十二卷《逐榜烽烟》')&&vol.includes('第1章　猎榜令'),'New volume directory missing');
assert.ok(vol.includes('全10章已发布')&&vol.includes('chapter-010.html'),'Complete volume must show all ten published chapters');
assert.ok(part.includes('volume-31.html')&&part.includes('volume-32.html'),'Fourth part must show completed and serializing volumes');
assert.ok(home.includes('330章＋序章')&&home.includes('第330章《路归众人》'),'Homepage must show latest published volume');
assert.ok(home.includes('chapters/volume-33/chapter-010.html'),'Latest home link missing');
const index=JSON.parse(read('assets/data/search-index.json'));
assert.equal(index.filter(e=>e.url===chapter).length,1,'Search index must contain published chapter once');
assert.equal(index.filter(e=>e.url==='volumes/volume-32.html').length,1,'Search index must contain volume once');
const search=read('search.html');
assert.ok(search.includes('v<=33')&&search.includes('x.p04?.max'),'New search index must honor spoiler gates');
const sitemap=read('sitemap.xml');
assert.ok(sitemap.includes(chapter)&&sitemap.includes('volumes/volume-32.html'),'Sitemap must include new chapter only');
assert.ok(sitemap.includes('volume-32/chapter-010.html')&&!sitemap.includes('volume-32/chapter-011.html'),'Sitemap must include chapters 311–320 but not 321');
const unlock=read('assets/js/progressive-archive.js'),jump=read('assets/js/home-relaunch.js'),reader=read('assets/js/reader-experience.js'),volScript=read('assets/js/volume-page.js');
assert.ok(unlock.includes("const KEY='zs:part-progress:v1'"),'Preserve per-part progress storage');
assert.ok(unlock.includes('p===4?30:100')&&unlock.includes('{p:4,n:11'),'Fourth arc must gate its 11th chapter separately');
assert.ok(jump.includes('num>330')&&jump.includes('current===4?3:10'),'Quick jump only exposes published chapters and volume cards');
assert.ok(reader.includes('globalChapter<330')&&reader.includes('vol<33'),'Reader must use latest published boundary');
assert.ok(volScript.includes('vol>32')&&volScript.includes('publishedCount'),'Volume layout must support partial updates');
for(const [name,script] of [['archive',unlock],['quick',jump],['reader',reader],['volume',volScript]])new Script(script,{filename:name+'.js'});
console.log('VOLUME32_CH311_PASS '+JSON.stringify({chapter:311,han,volumesPublished:32,publishedInVol32:10,spoilerIndependent:true}));
